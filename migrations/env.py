"""Alembic environment.

The database URL comes from the Alembic config (set by ``watchtower-db``) or
from WatchTower settings (``WATCHTOWER__DATABASE__URL``). New revisions should
be hand-reviewed: row-level security and triggers are not autogenerated.
"""

from __future__ import annotations

from alembic import context
from sqlalchemy import create_engine, pool

from watchtower.persistence.tables import metadata

config = context.config


def _url() -> str:
    url = config.get_main_option("sqlalchemy.url")
    if url:
        return url
    from watchtower.config import load_settings

    return load_settings().database.sqlalchemy_url()


def run_migrations_offline() -> None:
    context.configure(url=_url(), target_metadata=metadata, literal_binds=True, compare_type=True)
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    connection = config.attributes.get("connection")
    if connection is not None:
        _run(connection)
        return
    engine = create_engine(_url(), poolclass=pool.NullPool)
    with engine.connect() as connection:
        _run(connection)


def _run(connection) -> None:
    context.configure(
        connection=connection,
        target_metadata=metadata,
        compare_type=True,
        transaction_per_migration=True,
    )
    with context.begin_transaction():
        context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
